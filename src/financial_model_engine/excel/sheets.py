from openpyxl.worksheet.worksheet import Worksheet

from financial_model_engine.domain import ForecastPeriod, ModelAssumptions, Unit
from financial_model_engine.engine import LineItemResult, ModelCheck, ModelResult
from financial_model_engine.excel.cell_mapper import CellMapper
from financial_model_engine.excel.formatter import (
    ASSUMPTION_INPUT_FILL,
    GENERIC_VALUE_FORMAT,
    HEADER_FONT,
    NUMBER_FORMATS,
    TITLE_FONT,
    set_column_widths,
)

SHEET_NAMES = [
    "Cover",
    "Assumptions",
    "Operating Model",
    "Income Statement",
    "Balance Sheet",
    "Cash Flow",
    "Model Checks",
]

ASSUMPTION_UNITS: dict[str, Unit] = {
    "starting_customers": Unit.COUNT,
    "monthly_price": Unit.CURRENCY,
    "customer_growth": Unit.PERCENTAGE,
    "monthly_marketing": Unit.CURRENCY,
    "monthly_payroll": Unit.CURRENCY,
    "other_opex": Unit.CURRENCY,
    "initial_equity": Unit.CURRENCY,
    "tax_rate": Unit.PERCENTAGE,
    "forecast_months": Unit.COUNT,
}


def _label(field_name: str) -> str:
    return field_name.replace("_", " ").title()


def write_cover_sheet(worksheet: Worksheet, result: ModelResult) -> None:
    worksheet["A1"] = "3-Statement Financial Model"
    worksheet["A1"].font = TITLE_FONT

    worksheet["A3"] = "Generated by Financial Model Engine"
    worksheet["A4"] = f"Forecast periods: {len(result.periods)}"
    worksheet["A6"] = (
        "Assumptions are editable inputs. All financial outputs are generated "
        "by the model engine and should not be edited by hand."
    )
    set_column_widths(worksheet, {"A": 90})


def write_assumptions_sheet(
    worksheet: Worksheet, assumptions: ModelAssumptions, cell_mapper: CellMapper
) -> None:
    worksheet["A1"] = "Assumptions"
    worksheet["A1"].font = TITLE_FONT

    worksheet["A2"] = "Label"
    worksheet["B2"] = "Value"
    worksheet["A2"].font = HEADER_FONT
    worksheet["B2"].font = HEADER_FONT

    row = 3
    for field_name in ModelAssumptions.model_fields:
        unit = ASSUMPTION_UNITS[field_name]
        worksheet.cell(row=row, column=1, value=_label(field_name))
        value_cell = worksheet.cell(
            row=row, column=2, value=assumptions.__getattribute__(field_name)
        )
        value_cell.number_format = NUMBER_FORMATS[unit]
        value_cell.fill = ASSUMPTION_INPUT_FILL
        cell_mapper.map_assumption(field_name, "Assumptions", value_cell.coordinate)
        row += 1

    set_column_widths(worksheet, {"A": 24, "B": 16})


def write_line_items_sheet(
    worksheet: Worksheet,
    sheet_name: str,
    title: str,
    periods: list[ForecastPeriod],
    line_items: list[LineItemResult],
    cell_mapper: CellMapper,
) -> None:
    worksheet["A1"] = title
    worksheet["A1"].font = TITLE_FONT

    header_row = 3
    worksheet.cell(row=header_row, column=1, value="Line Item").font = HEADER_FONT
    for col_offset, period in enumerate(periods):
        cell = worksheet.cell(
            row=header_row, column=2 + col_offset, value=period.label
        )
        cell.font = HEADER_FONT

    for row_offset, line_item in enumerate(line_items):
        row = header_row + 1 + row_offset
        worksheet.cell(row=row, column=1, value=line_item.line_item_id)
        values_by_period = {pv.period_id: pv.value for pv in line_item.values}
        for col_offset, period in enumerate(periods):
            value = values_by_period.get(period.id)
            if value is None:
                continue
            cell = worksheet.cell(row=row, column=2 + col_offset, value=value)
            cell.number_format = GENERIC_VALUE_FORMAT
            cell_mapper.map_line_item(
                line_item.line_item_id, period.id, sheet_name, cell.coordinate
            )

    worksheet.freeze_panes = worksheet.cell(
        row=header_row + 1, column=2
    ).coordinate
    set_column_widths(
        worksheet, {"A": 24} | {chr(ord("B") + i): 14 for i in range(len(periods))}
    )


def write_checks_sheet(worksheet: Worksheet, checks: list[ModelCheck]) -> None:
    worksheet["A1"] = "Model Checks"
    worksheet["A1"].font = TITLE_FONT

    header_row = 3
    headers = ["Check", "Status", "Difference", "Message"]
    for col_offset, header in enumerate(headers):
        cell = worksheet.cell(row=header_row, column=1 + col_offset, value=header)
        cell.font = HEADER_FONT

    for row_offset, check in enumerate(checks):
        row = header_row + 1 + row_offset
        worksheet.cell(row=row, column=1, value=check.name)
        worksheet.cell(row=row, column=2, value="PASS" if check.passed else "FAIL")
        worksheet.cell(
            row=row,
            column=3,
            value=check.difference if check.difference is not None else "-",
        )
        worksheet.cell(row=row, column=4, value=check.message or "-")

    set_column_widths(worksheet, {"A": 28, "B": 10, "C": 14, "D": 32})
